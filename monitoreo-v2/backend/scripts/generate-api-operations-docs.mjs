#!/usr/bin/env node
/**
 * DAT-15 + DAT-21 + DAT-24: Generate API operations documentation.
 *
 * - DAT-15: Rate limiting documentation for PASA ETL
 * - DAT-21: Incremental data loading pattern (cursor/dateRange)
 * - DAT-24: Stale data alert configuration
 *
 * Usage:
 *   node scripts/generate-api-operations-docs.mjs [--output path]
 */

import { readFileSync, writeFileSync } from 'fs';
import { dirname, resolve } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const SRC_DIR = resolve(__dirname, '..', 'src');
const DEFAULT_OUTPUT = resolve(__dirname, '..', '..', '..', 'docs', 'context', 'api-operations.md');

/* ── Extract rate limit config from source ── */

function extractRateLimits(srcDir) {
  const mainTs = readFileSync(resolve(srcDir, 'main.ts'), 'utf-8');
  const appModule = readFileSync(resolve(srcDir, 'app.module.ts'), 'utf-8');

  const tiers = [];
  const tierRe = /\{\s*name:\s*'(\w+)',\s*ttl:\s*(\d+),\s*limit:\s*(\d+)\s*\}/g;
  let match;
  while ((match = tierRe.exec(appModule)) !== null) {
    tiers.push({ name: match[1], ttlMs: parseInt(match[2]), limit: parseInt(match[3]) });
  }

  const hasRedis = appModule.includes('REDIS_URL') || appModule.includes('ThrottlerStorageRedis');
  return { tiers, hasRedis };
}

/* ── Extract stale threshold from tenant-settings ── */

function extractStaleConfig(srcDir) {
  const settings = readFileSync(resolve(srcDir, 'lib', 'tenant-settings.ts'), 'utf-8');
  const defaultMatch = settings.match(/DEFAULT_STALE_THRESHOLD_HOURS\s*=\s*(\d+)/);
  const minMatch = settings.match(/MIN_STALE_THRESHOLD_HOURS\s*=\s*(\d+)/);
  const maxMatch = settings.match(/MAX_STALE_THRESHOLD_HOURS\s*=\s*(\d+)/);
  return {
    defaultHours: defaultMatch ? parseInt(defaultMatch[1]) : 4,
    minHours: minMatch ? parseInt(minMatch[1]) : 1,
    maxHours: maxMatch ? parseInt(maxMatch[1]) : 72,
  };
}

/* ── Markdown ── */

function generateMarkdown(srcDir) {
  const rateLimits = extractRateLimits(srcDir);
  const stale = extractStaleConfig(srcDir);

  const lines = [
    '# API Operations Guide — monitoreo-v2',
    '',
    `> Auto-generated by \`scripts/generate-api-operations-docs.mjs\`.`,
    '> Re-generate: `npm run docs:api-ops`',
    '',
    '---',
    '',
    '## 1. Rate Limiting (DAT-15)',
    '',
    '> Anexo 07 DAT-15: Documented API rate limits to prevent ETL blocking.',
    '',
    'The platform uses a tiered `ThrottlerGuard` (global, all endpoints).',
    '',
    '| Tier | Window | Limit | Scope |',
    '|------|-------:|------:|-------|',
  ];

  for (const t of rateLimits.tiers) {
    lines.push(`| ${t.name} | ${t.ttlMs / 1000}s | ${t.limit} req | Per IP (or per API key) |`);
  }

  lines.push('');
  lines.push('### API Key Rate Limits');
  lines.push('');
  lines.push('Each API key has a configurable `rate_limit_per_minute` (default 100).');
  lines.push('Exceeding the limit returns `429 Too Many Requests` with `Retry-After` header.');
  lines.push('');
  lines.push(`**Storage:** ${rateLimits.hasRedis ? 'Redis-backed (distributed, multi-instance safe)' : 'In-memory (single instance)'} when \`REDIS_URL\` is set.`);
  lines.push('');
  lines.push('### Recommendations for PASA ETL');
  lines.push('');
  lines.push('- Use **incremental loading** (see below) to minimize request volume');
  lines.push('- Request a dedicated API key with higher `rate_limit_per_minute` for bulk ETL');
  lines.push('- Implement exponential backoff on 429 responses');
  lines.push('- Prefer `/v1/readings/aggregated` over raw readings for analytics');
  lines.push('- Use `/v1/exports` for large dataset extraction (async job → download)');
  lines.push('');

  lines.push('---');
  lines.push('');
  lines.push('## 2. Incremental Data Loading (DAT-21)');
  lines.push('');
  lines.push('> Anexo 07 DAT-21: Support for incremental extraction (only new data since last query).');
  lines.push('');
  lines.push('### Pattern: Date Range Cursor');
  lines.push('');
  lines.push('All time-series endpoints accept `from` and `to` ISO 8601 parameters:');
  lines.push('');
  lines.push('```');
  lines.push('GET /api/v1/readings?meterId=<uuid>&from=2026-06-14T00:00:00Z&to=2026-06-15T00:00:00Z');
  lines.push('GET /api/v1/readings/aggregated?interval=hourly&from=2026-06-14T00:00:00Z&to=2026-06-15T00:00:00Z');
  lines.push('```');
  lines.push('');
  lines.push('### Recommended ETL Flow');
  lines.push('');
  lines.push('```');
  lines.push('1. Store last successful extraction timestamp (watermark)');
  lines.push('2. Query: from=watermark, to=NOW()');
  lines.push('3. Process response');
  lines.push('4. Update watermark to MAX(timestamp) from response');
  lines.push('5. Repeat on schedule (e.g., every 15 minutes)');
  lines.push('```');
  lines.push('');
  lines.push('### Latest Anchor');
  lines.push('');
  lines.push('Use `GET /api/v1/readings/latest-anchor` to get the newest reading timestamp.');
  lines.push('This avoids querying into the future and handles gaps.');
  lines.push('');
  lines.push('### Bulk Export (Async)');
  lines.push('');
  lines.push('For large extractions (>10K readings):');
  lines.push('');
  lines.push('```');
  lines.push('1. POST /api/v1/exports { format: "csv", from, to, meterId? }');
  lines.push('2. GET /api/v1/exports/:id  → poll until status = "completed"');
  lines.push('3. GET /api/v1/exports/:id/download  → stream CSV file');
  lines.push('```');
  lines.push('');
  lines.push('### Cursor-Based Pagination');
  lines.push('');
  lines.push('The streaming export endpoint supports cursor-based pagination:');
  lines.push('');
  lines.push('```');
  lines.push('GET /api/v1/readings/export?format=csv&from=...&to=...&cursor=<last_id>');
  lines.push('```');
  lines.push('');
  lines.push('Each response includes a `nextCursor` field. Pass it as `cursor` in the next request.');
  lines.push('');

  lines.push('---');
  lines.push('');
  lines.push('## 3. Stale Data Alerts (DAT-24)');
  lines.push('');
  lines.push('> Anexo 07 DAT-24: Automatic notification when data flow stops for > 4 hours.');
  lines.push('');
  lines.push('### Configuration');
  lines.push('');
  lines.push(`| Setting | Value | Range |`);
  lines.push(`|---------|------:|------:|`);
  lines.push(`| Default threshold | ${stale.defaultHours}h | — |`);
  lines.push(`| Minimum | ${stale.minHours}h | — |`);
  lines.push(`| Maximum | ${stale.maxHours}h | — |`);
  lines.push('');
  lines.push('Configurable per tenant via `settings.staleThresholdHours` in the tenants table.');
  lines.push('');
  lines.push('### Detection Mechanism');
  lines.push('');
  lines.push('```');
  lines.push('EventBridge (5 min) → Lambda offlineAlerts');
  lines.push('  → Query: meters with no reading in last N hours');
  lines.push('  → Create alert (type: METER_OFFLINE, severity: HIGH)');
  lines.push('  → Notify: email (SES) + webhook (if configured)');
  lines.push('```');
  lines.push('');
  lines.push('### Meter Reading Status');
  lines.push('');
  lines.push('`meter_reading_status` table tracks per-meter last reading timestamp.');
  lines.push('Queryable via `GET /api/v1/meters/:id/status` (external API).');
  lines.push('');
  lines.push('### Alert Response');
  lines.push('');
  lines.push('| Field | Value |');
  lines.push('|-------|-------|');
  lines.push('| `alert_type_code` | `METER_OFFLINE` |');
  lines.push('| `severity` | `HIGH` |');
  lines.push('| `auto_resolve` | Yes, when data resumes |');
  lines.push('| `notification` | Email + webhook |');
  lines.push('');

  return lines.join('\n');
}

/* ── Main ── */

export function generate(srcDir = SRC_DIR) {
  const markdown = generateMarkdown(srcDir);
  const rateLimits = extractRateLimits(srcDir);
  const stale = extractStaleConfig(srcDir);

  return {
    markdown,
    rateLimitTierCount: rateLimits.tiers.length,
    hasRedis: rateLimits.hasRedis,
    staleDefaultHours: stale.defaultHours,
  };
}

const isMain = process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url));
if (isMain) {
  const outputIdx = process.argv.indexOf('--output');
  const outputPath = outputIdx >= 0 ? resolve(process.argv[outputIdx + 1]) : DEFAULT_OUTPUT;

  const result = generate();
  writeFileSync(outputPath, result.markdown, 'utf-8');
  console.log(`API operations: ${result.rateLimitTierCount} rate limit tiers, stale threshold ${result.staleDefaultHours}h → ${outputPath}`);
}
