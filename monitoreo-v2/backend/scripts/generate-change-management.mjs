#!/usr/bin/env node
/**
 * CYB-15: Generate change management process document.
 *
 * Usage:
 *   node scripts/generate-change-management.mjs [--output path]
 */

import { readFileSync, writeFileSync, existsSync } from 'fs';
import { dirname, resolve } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..', '..', '..');
const DEFAULT_OUTPUT = resolve(ROOT, 'docs', 'ops', 'change-management.md');

/* ── Detect CI workflows ── */

function detectWorkflows() {
  const workflowDir = resolve(ROOT, '.github', 'workflows');
  const workflows = [];
  const candidates = [
    { file: 'deploy.yml', name: 'Build & Deploy', purpose: 'Frontend build + deploy on push to main' },
    { file: 'zap-dast.yml', name: 'OWASP ZAP DAST Scan', purpose: 'Weekly security scan against API' },
    { file: 'security-patch-v2.yml', name: 'Security Patch Deploy', purpose: 'Rotates secrets + deploys backend+frontend' },
    { file: 'drive-pipeline.yml', name: 'Drive Pipeline', purpose: 'Scheduled data ingest from Google Drive' },
  ];

  for (const c of candidates) {
    const path = resolve(workflowDir, c.file);
    workflows.push({ ...c, exists: existsSync(path) });
  }

  return workflows;
}

/* ── Detect test suites ── */

function detectTestConfig() {
  const backendPkg = resolve(ROOT, 'monitoreo-v2', 'backend', 'package.json');
  const frontendPkg = resolve(ROOT, 'monitoreo-v2', 'frontend', 'package.json');

  const checks = [];

  const bePkg = JSON.parse(readFileSync(backendPkg, 'utf-8'));
  checks.push({ name: 'Backend unit tests (Jest)', command: 'npm test', exists: !!bePkg.scripts?.test });
  checks.push({ name: 'Backend smoke tests', command: 'npm run test:smoke-dashboard', exists: !!bePkg.scripts?.['test:smoke-dashboard'] });

  const fePkg = JSON.parse(readFileSync(frontendPkg, 'utf-8'));
  checks.push({ name: 'Frontend unit tests (Vitest)', command: 'npm test', exists: !!fePkg.scripts?.test });

  return checks;
}

/* ── Generate markdown ── */

function generateMarkdown() {
  const workflows = detectWorkflows();
  const testChecks = detectTestConfig();
  const activeWorkflows = workflows.filter(w => w.exists);
  const activeTests = testChecks.filter(t => t.exists);

  const lines = [
    '# Change Management Process — monitoreo-v2',
    '',
    `> Auto-generated by \`scripts/generate-change-management.mjs\`.`,
    `> ${activeWorkflows.length} CI workflows, ${activeTests.length} test gates detected.`,
    '> Re-generate: `npm run docs:change-mgmt`',
    '',
    '> CYB-15 (Anexo 07): Formal change management process ensuring no modification',
    '> reaches production without security testing and prior approval.',
    '',
    '---',
    '',
    '## 1. Change Lifecycle',
    '',
    '```',
    'Feature Request / Bug Report',
    '  → Branch (feat/*, fix/*, refactor/*)',
    '    → Development (local + tests)',
    '      → Pull Request (code review + CI)',
    '        → Approval (1+ reviewer)',
    '          → Merge to main',
    '            → CI Build + Deploy',
    '              → Post-deploy verification',
    '```',
    '',
    '---',
    '',
    '## 2. Branch Strategy',
    '',
    '| Branch | Purpose | Protection |',
    '|--------|---------|------------|',
    '| `main` | Production-ready code | Requires PR, CI pass, 1+ approval |',
    '| `feat/*` | New features | Developer branch, rebased on main |',
    '| `fix/*` | Bug fixes | Developer branch |',
    '| `refactor/*` | Code improvements | Developer branch |',
    '',
    '---',
    '',
    '## 3. Pre-Merge Gates',
    '',
    '| Gate | Type | Mandatory | Tool |',
    '|------|------|:---------:|------|',
    '| Unit tests (backend) | Automated | Yes | Jest (1100+ tests) |',
    '| Unit tests (frontend) | Automated | Yes | Vitest (295+ tests) |',
    '| TypeScript compilation | Automated | Yes | `nest build` / `vite build` |',
    '| Lint / format | Manual | Recommended | ESLint |',
    '| Code review | Human | Yes | GitHub PR review |',
    '| Security review | Human | For auth/crypto changes | Security reviewer |',
    '| DAST scan | Automated (weekly) | Informational | OWASP ZAP |',
    '',
    '---',
    '',
    '## 4. CI/CD Workflows',
    '',
    '| Workflow | File | Trigger | Status |',
    '|---------|------|---------|--------|',
  ];

  for (const w of workflows) {
    const status = w.exists ? 'Active' : 'Not configured';
    lines.push(`| ${w.name} | \`${w.file}\` | ${w.purpose} | ${status} |`);
  }

  lines.push('');
  lines.push('---');
  lines.push('');
  lines.push('## 5. Test Suites');
  lines.push('');
  lines.push('| Suite | Command | Status |');
  lines.push('|-------|---------|--------|');

  for (const t of testChecks) {
    const status = t.exists ? 'Configured' : 'Not found';
    lines.push(`| ${t.name} | \`${t.command}\` | ${status} |`);
  }

  lines.push('');
  lines.push('---');
  lines.push('');
  lines.push('## 6. Deployment Process');
  lines.push('');
  lines.push('| Step | Action | Responsibility |');
  lines.push('|------|--------|----------------|');
  lines.push('| 1 | Merge PR to `main` | Developer + Reviewer |');
  lines.push('| 2 | CI builds Docker image → ECR | Automated (GitHub Actions) |');
  lines.push('| 3 | ECS deploys new task definition | Automated or manual trigger |');
  lines.push('| 4 | Frontend builds → S3 + CloudFront invalidation | Automated |');
  lines.push('| 5 | Apply DB migrations via ECS Exec | Manual (ops) |');
  lines.push('| 6 | Smoke test (`npm run test:smoke-dashboard`) | Manual (ops) |');
  lines.push('| 7 | Monitor CloudWatch for 30min post-deploy | Ops |');
  lines.push('');
  lines.push('---');
  lines.push('');
  lines.push('## 7. Rollback Procedure');
  lines.push('');
  lines.push('| Scenario | Action |');
  lines.push('|----------|--------|');
  lines.push('| Backend regression | Redeploy previous ECR image tag |');
  lines.push('| Frontend regression | Redeploy previous S3 build + invalidate CF |');
  lines.push('| Database migration issue | Apply rollback SQL (manual, documented per migration) |');
  lines.push('| Full rollback | Restore RDS from snapshot + redeploy previous images |');
  lines.push('');
  lines.push('---');
  lines.push('');
  lines.push('## 8. Emergency Changes');
  lines.push('');
  lines.push('For critical security patches or production-down scenarios:');
  lines.push('');
  lines.push('1. Hotfix branch from `main`');
  lines.push('2. Minimal fix + targeted tests');
  lines.push('3. Expedited review (1 reviewer, can be async)');
  lines.push('4. Deploy via `security-patch-v2.yml` or manual ECS update');
  lines.push('5. Post-mortem within 48h');
  lines.push('');

  return lines.join('\n');
}

export function generate() {
  const workflows = detectWorkflows();
  const testChecks = detectTestConfig();
  const markdown = generateMarkdown();

  return {
    markdown,
    workflowCount: workflows.filter(w => w.exists).length,
    testGateCount: testChecks.filter(t => t.exists).length,
    workflows: workflows.map(w => w.name),
    testSuites: testChecks.map(t => t.name),
  };
}

const isMain = process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url));
if (isMain) {
  const outputIdx = process.argv.indexOf('--output');
  const outputPath = outputIdx >= 0 ? resolve(process.argv[outputIdx + 1]) : DEFAULT_OUTPUT;

  const result = generate();
  writeFileSync(outputPath, result.markdown, 'utf-8');
  console.log(`Change management: ${result.workflowCount} workflows, ${result.testGateCount} test gates → ${outputPath}`);
}
