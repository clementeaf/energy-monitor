function generateMarkdown() {
  const lines = [
    '# Network Requirements — monitoreo-v2',
    '',
    `> Auto-generated by \`scripts/generate-network-requirements.mjs\`.`,
    `> ${CONNECTIONS.length} connection types, ${FIREWALL_RULES.length} firewall rules.`,
    '> Re-generate: `npm run docs:network-reqs`',
    '',
    '> ARQ-18 (Anexo 07): Minimum connectivity requirements for mall operation.',
    '',
    '---',
    '',
    '## Minimum Bandwidth per Mall',
    '',
    '| Scenario | Minimum | Recommended |',
    '|----------|--------:|------------:|',
    '| 1–50 meters, 5 concurrent users | 5 Mbps | 10 Mbps |',
    '| 50–200 meters, 10 concurrent users | 10 Mbps | 20 Mbps |',
    '| 200+ meters, 20 concurrent users | 20 Mbps | 50 Mbps |',
    '',
    '**Latency:** < 200ms RTT to AWS us-east-1 for acceptable dashboard performance.',
    '',
    '---',
    '',
    '## Connection Types',
    '',
  ];

  for (const c of CONNECTIONS) {
    lines.push(`### ${c.name}`);
    lines.push('');
    lines.push('| Aspect | Detail |');
    lines.push('|--------|--------|');
    lines.push(`| **Direction** | ${c.direction} |`);
    lines.push(`| **Protocol** | ${c.protocol} |`);
    lines.push(`| **Port** | ${c.port} |`);
    lines.push(`| **Destination** | ${c.destination} |`);
    lines.push(`| **Bandwidth** | ${c.bandwidth} |`);
    lines.push(`| **Latency** | ${c.latency} |`);
    lines.push(`| **Notes** | ${c.note} |`);
    lines.push('');
  }

  lines.push('---');
  lines.push('');
  lines.push('## Firewall Rules (Minimum)');
  lines.push('');
  lines.push('| Direction | Port | Protocol | Destination | Purpose |');
  lines.push('|-----------|-----:|----------|-------------|---------|');

  for (const r of FIREWALL_RULES) {
    lines.push(`| ${r.direction} | ${r.port} | ${r.protocol} | ${r.destination} | ${r.purpose} |`);
  }

  lines.push('');
  lines.push('---');
  lines.push('');
  lines.push('## Connectivity Resilience');
  lines.push('');
  lines.push('| Feature | Behavior |');
  lines.push('|---------|----------|');
  lines.push('| MQTT offline buffer | Device buffers readings locally, pushes on reconnect |');
  lines.push('| Backfill | Platform auto-detects gaps and backfills from device/S3 |');
  lines.push('| Stale data alert | Notification if no data received for > 4h (configurable) |');
  lines.push('| Frontend offline | SPA cached in browser, shows last-known data |');
  lines.push('');

  return lines.join('\n');
}

export function generate() {
  const markdown = generateMarkdown();
  return {
    markdown,
    connectionCount: CONNECTIONS.length,
    firewallRuleCount: FIREWALL_RULES.length,
    connections: CONNECTIONS.map(c => c.name),
    ports: [...new Set(CONNECTIONS.map(c => c.port))].filter(p => typeof p === 'number').sort((a, b) => Number(a) - Number(b)),
  };
}

const isMain = process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url));
if (isMain) {
  const outputIdx = process.argv.indexOf('--output');
  const outputPath = outputIdx >= 0 ? resolve(process.argv[outputIdx + 1]) : DEFAULT_OUTPUT;

  const result = generate();
  writeFileSync(outputPath, result.markdown, 'utf-8');
  console.log(`Network requirements: ${result.connectionCount} connections, ${result.firewallRuleCount} firewall rules → ${outputPath}`);
}
