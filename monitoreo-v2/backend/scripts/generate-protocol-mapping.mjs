#!/usr/bin/env node
/**
 * INT-14: Generate protocol-to-API data mapping document.
 *
 * Usage:
 *   node scripts/generate-protocol-mapping.mjs [--output path]
 *
 * Reads protocol constants, IoT variable mappings, reading entity fields,
 * quality mapping, and reading sources from backend source code.
 * Outputs a structured Markdown transformation matrix.
 */

import { readFileSync, writeFileSync } from 'fs';
import { dirname, resolve } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const SRC_DIR = resolve(__dirname, '..', 'src');
const DEFAULT_OUTPUT = resolve(__dirname, '..', '..', '..', 'docs', 'context', 'protocol-mapping.md');

/* ── Source extraction ── */

function extractArrayConst(source, name) {
  const re = new RegExp(`${name}\\s*=\\s*\\[([^\\]]+)\\]`, 's');
  const match = source.match(re);
  if (!match) return [];
  return match[1]
    .replace(/['"`]/g, '')
    .split(',')
    .map(s => s.trim())
    .filter(Boolean);
}

function extractIotMappings(source) {
  const entries = [];
  const re = /\{\s*registerKey:\s*'([^']+)',\s*targetField:\s*'([^']+)',\s*scaleFactor:\s*([\d.]+)(?:,\s*unit:\s*'([^']*)')?\s*\}/g;
  let match;
  while ((match = re.exec(source)) !== null) {
    entries.push({
      registerKey: match[1],
      targetField: match[2],
      scaleFactor: parseFloat(match[3]),
      unit: match[4] ?? null,
    });
  }
  return entries;
}

function extractReadingColumns(source) {
  const columns = [];
  const re = /name:\s*'([^']+)'.*?type:\s*'([^']+)'(?:.*?precision:\s*(\d+))?(?:.*?scale:\s*(\d+))?/g;
  let match;
  while ((match = re.exec(source)) !== null) {
    columns.push({
      name: match[1],
      type: match[2],
      precision: match[3] ? parseInt(match[3]) : null,
      scale: match[4] ? parseInt(match[4]) : null,
    });
  }
  return columns;
}

/**
 * Hardcoded quality map — matches mapIotQualityToReadingQuality() logic.
 * Extracted from TSDoc rather than regex to avoid header-separator noise.
 */
function extractQualityMap() {
  return [
    { iotValue: '0', meaning: 'Good / measured', readingQuality: 'measured' },
    { iotValue: '1', meaning: 'Uncertain', readingQuality: 'estimated' },
    { iotValue: '2+', meaning: 'Bad / offline', readingQuality: 'invalid' },
    { iotValue: 'null', meaning: 'Not set', readingQuality: 'unknown' },
  ];
}

/* ── Read all sources ── */

function readSources(srcDir) {
  const protocolMapping = readFileSync(resolve(srcDir, 'common/constants/protocol-mapping.ts'), 'utf-8');
  const readingQuality = readFileSync(resolve(srcDir, 'common/constants/reading-quality.ts'), 'utf-8');
  const iotMappings = readFileSync(resolve(srcDir, 'lib/iot-variable-mappings.ts'), 'utf-8');
  const readingEntity = readFileSync(resolve(srcDir, 'modules/platform/entities/reading.entity.ts'), 'utf-8');

  return {
    protocols: extractArrayConst(protocolMapping, 'PROTOCOL_TYPE_CODES'),
    targetFields: extractArrayConst(protocolMapping, 'READING_TARGET_FIELDS'),
    deviceProfiles: extractArrayConst(protocolMapping, 'DEVICE_PROFILES'),
    qualities: extractArrayConst(readingQuality, 'READING_QUALITIES'),
    sources: extractArrayConst(readingQuality, 'READING_SOURCES'),
    qualityMap: extractQualityMap(),
    siemensMappings: extractIotMappings(iotMappings),
    readingColumns: extractReadingColumns(readingEntity),
  };
}

/* ── Markdown generation ── */

function generateMarkdown(data) {
  const lines = [
    '# Protocol-to-API Data Mapping — monitoreo-v2',
    '',
    '> Auto-generated by `scripts/generate-protocol-mapping.mjs`.',
    '> Re-generate: `npm run db:protocol-mapping`',
    '',
    '> INT-14: Transformation matrix from field protocols (Modbus/BACnet/MQTT) to API data model.',
    '',
    '## Supported Protocols',
    '',
    '| Code | Description |',
    '|------|-------------|',
  ];

  const protoDesc = {
    modbus: 'Modbus TCP/RTU — industrial meter communication (PAC series)',
    mqtt: 'MQTT over TLS — IoT Core ingestion (Siemens POC3000)',
    bacnet: 'BACnet/IP — building automation protocol',
    snmp: 'SNMP — network device monitoring',
    api: 'REST API — external system ingress',
  };

  for (const p of data.protocols) {
    lines.push(`| \`${p}\` | ${protoDesc[p] ?? p} |`);
  }

  lines.push('');
  lines.push('## Device Profiles');
  lines.push('');
  lines.push(`Registered profiles: ${data.deviceProfiles.map(p => `\`${p}\``).join(', ')}`);
  lines.push('');

  lines.push('---');
  lines.push('');
  lines.push('## MQTT / Siemens POC3000 — Variable Mapping');
  lines.push('');
  lines.push('Source: `lib/iot-variable-mappings.ts` → `NormalizationService.apply()`');
  lines.push('');
  lines.push('| IoT Variable (register_key) | API Field (target_field) | Scale Factor | Output Unit | Transformation |');
  lines.push('|-----------------------------|--------------------------|-------------:|-------------|----------------|');

  for (const m of data.siemensMappings) {
    const transform = m.scaleFactor === 1
      ? 'Direct pass-through'
      : `Multiply by ${m.scaleFactor} (${m.scaleFactor < 1 ? 'divide' : 'multiply'})`;
    lines.push(`| \`${m.registerKey}\` | \`${m.targetField}\` | ${m.scaleFactor} | ${m.unit ?? '—'} | ${transform} |`);
  }

  lines.push('');
  lines.push('### Transformation Pipeline');
  lines.push('');
  lines.push('```');
  lines.push('IoT Core MQTT → S3 (raw JSON) → Lambda iot-ingest → iot_readings (EAV)');
  lines.push('  → NormalizationService.apply(mappings, raw)');
  lines.push('  → coerceNumber(value) × scaleFactor → readings table (normalized)');
  lines.push('```');
  lines.push('');

  lines.push('---');
  lines.push('');
  lines.push('## Reading Target Fields');
  lines.push('');
  lines.push('Canonical fields in the `readings` table that all protocols map to:');
  lines.push('');
  lines.push('| Field | Unit | Description |');
  lines.push('|-------|------|-------------|');

  const fieldDesc = {
    power_kw: ['kW', 'Active power (3-phase total)'],
    reactive_power_kvar: ['kVAR', 'Reactive power'],
    power_factor: ['—', 'Power factor (0–1)'],
    frequency_hz: ['Hz', 'Grid frequency'],
    energy_kwh_total: ['kWh', 'Cumulative energy import'],
    voltage_l1: ['V', 'Phase L1 voltage'],
    voltage_l2: ['V', 'Phase L2 voltage'],
    voltage_l3: ['V', 'Phase L3 voltage'],
    current_l1: ['A', 'Phase L1 current'],
    current_l2: ['A', 'Phase L2 current'],
    current_l3: ['A', 'Phase L3 current'],
    thd_voltage_pct: ['%', 'Total harmonic distortion (voltage)'],
    thd_current_pct: ['%', 'Total harmonic distortion (current)'],
    phase_imbalance_pct: ['%', 'Phase imbalance'],
  };

  for (const f of data.targetFields) {
    const [unit, desc] = fieldDesc[f] ?? ['—', f];
    lines.push(`| \`${f}\` | ${unit} | ${desc} |`);
  }

  lines.push('');
  lines.push('---');
  lines.push('');
  lines.push('## Data Quality Classification');
  lines.push('');
  lines.push('Each reading carries a `quality` enum (Ley 21.719 / DAT-06 compliance):');
  lines.push('');
  lines.push('| Quality | Description | When assigned |');
  lines.push('|---------|-------------|---------------|');

  const qualityDesc = {
    measured: ['Direct hardware measurement', 'Normal ingest from meter via any protocol'],
    estimated: ['Interpolated or calculated value', 'Backfill, gap interpolation, or uncertain IoT quality=1'],
    invalid: ['Failed validation or corrupt', 'Out-of-range, CRC error, or IoT quality≥2'],
    unknown: ['Quality not determined', 'Legacy data or source without quality metadata'],
  };

  for (const q of data.qualities) {
    const [desc, when] = qualityDesc[q] ?? [q, '—'];
    lines.push(`| \`${q}\` | ${desc} | ${when} |`);
  }

  lines.push('');
  lines.push('### IoT Quality → Reading Quality Mapping');
  lines.push('');
  lines.push('Source: `common/constants/reading-quality.ts` → `mapIotQualityToReadingQuality()`');
  lines.push('');
  lines.push('| IoT quality (int) | Meaning | reading_quality |');
  lines.push('|------------------:|---------|-----------------|');

  for (const q of data.qualityMap) {
    lines.push(`| ${q.iotValue} | ${q.meaning} | \`${q.readingQuality}\` |`);
  }

  lines.push('');
  lines.push('---');
  lines.push('');
  lines.push('## Reading Sources');
  lines.push('');
  lines.push('The `source` column on each reading identifies the ingest origin:');
  lines.push('');
  lines.push('| Source | Description |');
  lines.push('|--------|-------------|');

  const sourceDesc = {
    modbus: 'Modbus TCP/RTU polling (PAC series meters)',
    mqtt: 'MQTT IoT Core (Siemens POC3000)',
    api_ingress: 'External REST API push (POST /v1/measurements)',
    backfill: 'Automated gap backfill after connectivity recovery',
    synthetic: 'Synthetic readings generator (dev/demo)',
    drive_pipeline: 'Google Drive CSV pipeline (PASA bulk ingest)',
  };

  for (const s of data.sources) {
    lines.push(`| \`${s}\` | ${sourceDesc[s] ?? s} |`);
  }

  lines.push('');
  lines.push('---');
  lines.push('');
  lines.push('## Register Mapping Model');
  lines.push('');
  lines.push('Custom mappings per tenant/device are stored in `register_mappings`:');
  lines.push('');
  lines.push('```');
  lines.push('register_mappings {');
  lines.push('  protocol      — Protocol code (modbus, mqtt, bacnet, snmp, api)');
  lines.push('  device_profile — Hardware model (pac1670, siemens-poc3000, custom)');
  lines.push('  register_key  — Raw field name from device (e.g., "active_power_w")');
  lines.push('  target_field  — Normalized readings column (e.g., "power_kw")');
  lines.push('  scale_factor  — Multiplication factor (e.g., 0.001 for W→kW)');
  lines.push('  unit          — Output unit label (e.g., "kW")');
  lines.push('  tenant_id     — NULL = global template, UUID = tenant-specific override');
  lines.push('}');
  lines.push('```');
  lines.push('');

  return lines.join('\n');
}

/* ── Main ── */

export function generate(srcDir = SRC_DIR) {
  const data = readSources(srcDir);
  const markdown = generateMarkdown(data);

  return {
    markdown,
    protocolCount: data.protocols.length,
    targetFieldCount: data.targetFields.length,
    mappingCount: data.siemensMappings.length,
    qualityCount: data.qualities.length,
    sourceCount: data.sources.length,
    protocols: data.protocols,
    targetFields: data.targetFields,
  };
}

const isMain = process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url));
if (isMain) {
  const outputIdx = process.argv.indexOf('--output');
  const outputPath = outputIdx >= 0 ? resolve(process.argv[outputIdx + 1]) : DEFAULT_OUTPUT;

  const result = generate();
  writeFileSync(outputPath, result.markdown, 'utf-8');
  console.log(`Protocol mapping: ${result.protocolCount} protocols, ${result.mappingCount} variable mappings, ${result.targetFieldCount} target fields → ${outputPath}`);
}
